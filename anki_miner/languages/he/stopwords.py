"""Hebrew function-word tier (spec F.2): the words ``pos2="stopword"`` marks, so ``excluded_subtypes`` drops them.

``HE_STOPWORDS`` is generated, never hand-edited. Source: stopwords-iso ``stopwords-he`` (MIT,
Copyright (c) 2016 Gene Diaz; notice in ``licenses/stopwords-iso/LICENSE``), 194 words, 1,655 B
from ``https://cdn.jsdelivr.net/gh/stopwords-iso/stopwords-he@master/stopwords-he.txt``. It ships
as a frozenset rather than a data file (the id precedent): every entry is a plain Hebrew letter, so
nothing here needs package data, a wheel-asset row or a MANIFEST line.

Measured against ``he_50k``: 36 of its 50 commonest forms are stopwords-iso entries. The 14 that are
not include content words (``tov``, ``rotze``, ``yodea``) that must stay mineable, and proclitic
forms the ladder demotes on its own -- which is why this list is used as written and not extended
with anything the dictionary calls a noun, verb or adjective.

``HE_PARTICLES`` is first-party: the interjections, greetings and discourse fillers a subtitle
writes. Probed against the same dictionary before it was fixed -- four candidates were dropped
because each carried an ``adv`` lemma row, and the ones that stay despite a row are the ones the
spec names. Both sets are matched on the FOLDED surface, so a pointed spelling reaches them too,
and both are a DEFAULT: ``stopword`` is a subtype the POS editor offers.
"""

